#!/bin/bash
# Usage: build/manifest.sh [tag]. Generates the CRD, the RBAC and the Deployment from the code with the KubeOps CLI into
# deploy/generated, then renders deploy/kustomization.yaml into deploy/chroma-operator.yaml, the single file to apply.
# Needs kubectl 1.27 or later for kustomize v5; it reads no cluster.
set -euo pipefail
cd "$(dirname "$0")/.."
tag=${1:-dev}
kubectl=${KUBECTL:-kubectl}
dotnet tool restore >/dev/null
# The CLI compiles the project: its packages must be restored, also on a machine that has not built it, as in the release.
dotnet restore src/ChromaDotNet.Operator/ChromaDotNet.Operator.csproj >/dev/null
dotnet kubeops generate operator chroma-operator src/ChromaDotNet.Operator/ChromaDotNet.Operator.csproj --out deploy/generated \
  --clear-out --docker-image ghcr.io/chromadotnet/chroma-operator --docker-image-tag "$tag" --no-ansi >/dev/null
# The Dockerfile of the CLI is not used: the one at the root builds the image.
rm -f deploy/generated/Dockerfile
sed -i "s/newTag: .*/newTag: $tag/" deploy/kustomization.yaml
{
  echo "# ChromaDotNet.Operator $tag. Community project, not affiliated with Chroma. Generated by build/manifest.sh: do not edit."
  "$kubectl" kustomize deploy
} > deploy/chroma-operator.yaml
echo "deploy/chroma-operator.yaml: $(grep -c '^kind:' deploy/chroma-operator.yaml) objects"
